def calculate_month_threshold_rr(df: pd.DataFrame, method: str) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Calculate RR/log2RR/p-value for:
        basin × month × threshold × phase

    Thresholds are calculated separately for each basin and calendar month.
    """
    rng = np.random.default_rng(CFG.RANDOM_SEED)
    rows = []
    thr_rows = []

    for basin in CFG.BASIN_ORDER:
        bdf = df[df["basin"] == basin].copy()
        if bdf.empty:
            warnings.warn(f"No data for basin: {basin}")
            continue

        for month in range(1, 13):
            bm = bdf[bdf["month"] == month].copy()
            vals = bm["metric"].values.astype(float)
            vals = vals[np.isfinite(vals)]

            if len(vals) < 10:
                warnings.warn(f"Too few samples for threshold: {basin}, month={month}")
                continue

            for q in CFG.THRESHOLDS:
                threshold_value = float(np.nanpercentile(vals, q))
                thr_rows.append({
                    "method": method,
                    "basin": basin,
                    "month": month,
                    "threshold": int(q),
                    "threshold_value": threshold_value,
                    "metric_type": "calendar-month anomaly",
                    "metric_units": "mm",
                })

                bm_q = bm.copy()
                bm_q["event"] = (bm_q["metric"].astype(float) >= threshold_value).astype(int)

                neutral = bm_q[bm_q["phase"] == "Neutral"]
                n0 = len(neutral)
                c0 = int(neutral["event"].sum()) if n0 > 0 else 0

                for phase in CFG.PHASES:
                    ph = bm_q[bm_q["phase"] == phase]
                    n1 = len(ph)
                    c1 = int(ph["event"].sum()) if n1 > 0 else 0

                    if n1 < CFG.MIN_PHASE_N or n0 < CFG.MIN_NEUTRAL_N:
                        rr, log2rr, p1, p0 = np.nan, np.nan, np.nan, np.nan
                        pval, n_perm_valid = np.nan, 0
                    else:
                        rr, log2rr, p1, p0 = safe_log2_rr(
                            c1, n1, c0, n0,
                            use_correction=CFG.USE_HALDANE_ZERO_CORRECTION,
                        )

                        if CFG.RUN_PERMUTATION and np.isfinite(log2rr):
                            pval, _, n_perm_valid = permutation_p_value(
                                ph["event"].values,
                                neutral["event"].values,
                                rng,
                            )
                        else:
                            pval, n_perm_valid = np.nan, 0

                    rows.append({
                        "method": method,
                        "basin": basin,
                        "basin_short": CFG.BASIN_SHORT.get(basin, basin),
                        "month": int(month),
                        "month_label": CFG.MONTH_LABELS[month - 1],
                        "threshold": int(q),
                        "threshold_value": threshold_value,
                        "phase": phase,
                        "phase_label": CFG.PHASE_LABELS.get(phase, phase),
                        "n_phase": int(n1),
                        "count_phase": int(c1),
                        "P_phase": float(p1) if np.isfinite(p1) else np.nan,
                        "n_neutral": int(n0),
                        "count_neutral": int(c0),
                        "P_neutral": float(p0) if np.isfinite(p0) else np.nan,
                        "RR": float(rr) if np.isfinite(rr) else np.nan,
                        "log2RR": float(log2rr) if np.isfinite(log2rr) else np.nan,
                        "p_value": float(pval) if np.isfinite(pval) else np.nan,
                        "significant": bool(np.isfinite(pval) and pval < CFG.P_ALPHA),
                        "n_perm_valid": int(n_perm_valid),
                        "metric_type": "calendar-month anomaly",
                        "metric_units": "mm",
                    })

    risk = pd.DataFrame(rows)
    thresholds = pd.DataFrame(thr_rows)
    return risk, thresholds


