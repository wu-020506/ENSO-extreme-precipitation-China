def rr_to_equal_position(rr: np.ndarray) -> np.ndarray:
    """
    Transform RR values to equal-spaced colorbar positions.

    The colorbar labels are [0.2, 0.3, 0.4, 0.5, 1, 1.5, 2, 3, 4],
    but they are shown at equal visual spacing. This function maps real RR
    values onto those equally spaced positions using interpolation.
    """
    ticks = np.asarray(CFG.RR_TICKS, dtype=float)
    pos = np.arange(len(ticks), dtype=float)

    out = np.full_like(rr, np.nan, dtype=float)
    ok = np.isfinite(rr)
    if np.any(ok):
        out[ok] = np.interp(rr[ok], ticks, pos, left=pos[0], right=pos[-1])
    return out


def cmap_norm_equal() -> Tuple[mcolors.ListedColormap, mcolors.BoundaryNorm, List[float], List[str]]:
    """
    Equal-interval visual RR color scale.
    RR values are transformed to equal tick positions by rr_to_equal_position().
    """
    cmap = mcolors.ListedColormap(list(CFG.RR_COLORS), name="RR_equal_interval_clean")
    cmap.set_bad((1, 1, 1, 0))
    bounds = np.arange(len(CFG.RR_TICKS) + 1, dtype=float) - 0.5
    norm = mcolors.BoundaryNorm(bounds, cmap.N, clip=True)
    tick_pos = list(range(len(CFG.RR_TICKS)))
    tick_lab = [str(v) for v in CFG.RR_TICKS]
    return cmap, norm, tick_pos, tick_lab


def overlay_boolean(ax, lon: np.ndarray, lat: np.ndarray, mask: np.ndarray, color: str, zorder: int) -> None:
    if not np.any(mask):
        return
    cmap = mcolors.ListedColormap([color])
    data = np.where(mask, 1.0, np.nan)
    ax.pcolormesh(
        lon,
        lat,
        data,
        cmap=cmap,
        shading="nearest",
        transform=ccrs.PlateCarree(),
        zorder=zorder,
        antialiased=False,
    )



def _plot_outline_only(gdf: gpd.GeoDataFrame, ax, color: str, linewidth: float,
                       linestyle="-", zorder: int = 10) -> None:
    """
    Plot line geometries only.

    This helper is used especially for the ten-dash line. It intentionally
    removes point and polygon geometries before plotting, so grey dots or grey
    polygon/buffer patches around the ten-dash line will not appear.
    """
    if gdf is None or gdf.empty:
        return

    gdf2 = gdf[gdf.geometry.notnull()].copy()
    if gdf2.empty:
        return

    gdf2 = gdf2.explode(index_parts=False).reset_index(drop=True)
    gdf2 = gdf2[gdf2.geometry.geom_type.isin(["LineString", "MultiLineString"])].copy()

    if gdf2.empty:
        return

    gdf2.plot(
        ax=ax,
        color=color,
        linewidth=linewidth,
        linestyle=linestyle,
        transform=ccrs.PlateCarree(),
        zorder=zorder,
    )



def _geometry_to_line_only(gdf: gpd.GeoDataFrame, polygon_to_boundary: bool = True) -> gpd.GeoDataFrame:
    """
    Convert a vector layer to line-only geometries.
    Point/MultiPoint geometries are dropped. Polygon/MultiPolygon geometries are
    converted to boundaries only when polygon_to_boundary=True.
    """
    if gdf is None or gdf.empty:
        return gpd.GeoDataFrame(geometry=[], crs="EPSG:4326")
    gdf2 = gdf[gdf.geometry.notnull()].copy()
    if gdf2.empty:
        return gpd.GeoDataFrame(geometry=[], crs=getattr(gdf, "crs", "EPSG:4326"))
    try:
        gdf2 = gdf2.explode(index_parts=False).reset_index(drop=True)
    except Exception:
        pass
    geoms = []
    for geom in gdf2.geometry:
        if geom is None or geom.is_empty:
            continue
        gt = geom.geom_type
        if gt in ("LineString", "MultiLineString"):
            geoms.append(geom)
        elif polygon_to_boundary and gt in ("Polygon", "MultiPolygon"):
            geoms.append(geom.boundary)
