def get_variable(ds: xr.Dataset, base: str, suffix: str, required: bool = True) -> Optional[np.ndarray]:
    name = f"{base}_{suffix}"
    if name in ds:
        return ds[name].values

    # robust fallback for older files
    fallback_names = {
        "sig_display": [f"{base}_sig_final", f"{base}_sig_wilson", f"{base}_sig_fdr"],
        "never_event": [f"{base}_never_phase"],
    }

    for fb in fallback_names.get(suffix, []):
        if fb in ds:
            return ds[fb].values

    if required:
        raise KeyError(f"Variable not found in NetCDF: {name}")
    return None


def get_panel_data(ds: xr.Dataset, q: int, month: int, phase: str, china_mask: np.ndarray) -> Dict[str, np.ndarray]:
    phase_key = PHASE_KEY[phase]
    base = f"q{q}_{MONTH_LABEL[month]}_{phase_key}"

    rr = get_variable(ds, base, "RR", required=True).astype(float)

    sig = get_variable(ds, base, "sig_display", required=True).astype(bool)
    sig = sig & china_mask

    never_neutral = get_variable(ds, base, "never_neutral", required=False)
    never_event = get_variable(ds, base, "never_event", required=False)
    never_either = get_variable(ds, base, "never_either", required=False)

    if never_neutral is None:
        never_neutral = np.zeros_like(sig, dtype=bool)
    else:
        never_neutral = never_neutral.astype(bool) & sig

    if never_event is None:
        never_event = np.zeros_like(sig, dtype=bool)
    else:
        never_event = never_event.astype(bool) & sig

    if never_either is None:
        never_either = never_neutral & never_event
    else:
        never_either = never_either.astype(bool) & sig

    return {
        "rr": rr,
        "sig": sig,
        "never_neutral": never_neutral,
        "never_event": never_event,
        "never_either": never_either,
    }



