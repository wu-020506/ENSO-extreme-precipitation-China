def wilson_interval(c: np.ndarray, n: np.ndarray, alpha: float = 0.05) -> Tuple[np.ndarray, np.ndarray]:
    """
    Wilson score interval for binomial event probability.
    """
    z = 1.959963984540054
    c = c.astype(float)
    n = n.astype(float)

    lo = np.full_like(c, np.nan, dtype=float)
    hi = np.full_like(c, np.nan, dtype=float)

    valid = n > 0
    p = np.divide(c, n, out=np.full_like(c, np.nan), where=n > 0)

    denom = 1.0 + z**2 / n
    centre = (p + z**2 / (2.0 * n)) / denom
    half = z * np.sqrt((p * (1.0 - p) + z**2 / (4.0 * n)) / n) / denom

    lo[valid] = centre[valid] - half[valid]
    hi[valid] = centre[valid] + half[valid]
    return lo, hi


def calculate_rr_from_counts(c_phase: np.ndarray, n_phase: np.ndarray,
                             c_neutral: np.ndarray, n_neutral: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """
    Calculate RR and log2(RR) from event counts.

    Haldane correction is used only when either event count is zero, avoiding
    infinite RR values while keeping nonzero cases as raw probabilities.
    """
    c_phase = c_phase.astype(float)
    n_phase = n_phase.astype(float)
    c_neutral = c_neutral.astype(float)
    n_neutral = n_neutral.astype(float)

    p_phase = np.divide(c_phase, n_phase, out=np.full_like(c_phase, np.nan), where=n_phase > 0)
    p_neutral = np.divide(c_neutral, n_neutral, out=np.full_like(c_neutral, np.nan), where=n_neutral > 0)

    zero_case = (c_phase == 0) | (c_neutral == 0)
    p_phase_corr = np.where(zero_case, (c_phase + 0.5) / (n_phase + 1.0), p_phase)
    p_neutral_corr = np.where(zero_case, (c_neutral + 0.5) / (n_neutral + 1.0), p_neutral)

    rr = np.divide(p_phase_corr, p_neutral_corr, out=np.full_like(p_phase_corr, np.nan), where=p_neutral_corr > 0)
    log2rr = np.log2(rr)
    return rr, log2rr


def aggregate_season_from_monthly_counts(ds: xr.Dataset, q: int,
                                         months: Tuple[int, ...],
                                         phase: str) -> Dict[str, np.ndarray]:
    """
    Aggregate monthly count variables into a seasonal event-probability test.
    """
    phase_key = PHASE_KEY[phase]

    c_phase_sum = None
    n_phase_sum = None
    c_neutral_sum = None
    n_neutral_sum = None

    for m in months:
        base = f"q{q}_{MONTH_LABEL[m]}_{phase_key}"

        c_phase = get_variable(ds, base, "c_phase", required=True).astype(float)
        n_phase = get_variable(ds, base, "n_phase", required=True).astype(float)
        c_neutral = get_variable(ds, base, "c_neutral", required=True).astype(float)
        n_neutral = get_variable(ds, base, "n_neutral", required=True).astype(float)

        if c_phase_sum is None:
            c_phase_sum = np.zeros_like(c_phase, dtype=float)
            n_phase_sum = np.zeros_like(n_phase, dtype=float)
            c_neutral_sum = np.zeros_like(c_neutral, dtype=float)
            n_neutral_sum = np.zeros_like(n_neutral, dtype=float)

        c_phase_sum += np.nan_to_num(c_phase, nan=0.0)
        n_phase_sum += np.nan_to_num(n_phase, nan=0.0)
        c_neutral_sum += np.nan_to_num(c_neutral, nan=0.0)
        n_neutral_sum += np.nan_to_num(n_neutral, nan=0.0)

    rr, log2rr = calculate_rr_from_counts(c_phase_sum, n_phase_sum, c_neutral_sum, n_neutral_sum)

    p_phase = np.divide(c_phase_sum, n_phase_sum, out=np.full_like(c_phase_sum, np.nan), where=n_phase_sum > 0)
    p_neutral = np.divide(c_neutral_sum, n_neutral_sum, out=np.full_like(c_neutral_sum, np.nan), where=n_neutral_sum > 0)
    ci_low, ci_high = wilson_interval(c_phase_sum, n_phase_sum, alpha=0.05)

    sig = (
        np.isfinite(p_phase) &
        np.isfinite(p_neutral) &
        np.isfinite(ci_low) &
        np.isfinite(ci_high) &
        ((p_neutral < ci_low) | (p_neutral > ci_high))
    )

    never_neutral = (c_neutral_sum == 0) & (n_neutral_sum > 0)
    never_event = (c_phase_sum == 0) & (n_phase_sum > 0)
    never_either = never_neutral & never_event

    return {
        "RR": rr,
        "log2RR": log2rr,
        "P_phase": p_phase,
        "P_neutral": p_neutral,
        "wilson_ci_low": ci_low,
        "wilson_ci_high": ci_high,
        "sig_wilson": sig.astype(np.int8),
        "never_neutral": never_neutral.astype(np.int8),
        "never_event": never_event.astype(np.int8),
        "never_either": never_either.astype(np.int8),
        "c_phase": c_phase_sum.astype(np.int16),
        "n_phase": n_phase_sum.astype(np.int16),
        "c_neutral": c_neutral_sum.astype(np.int16),
        "n_neutral": n_neutral_sum.astype(np.int16),
    }


def build_seasonal_dataset(ds_monthly: xr.Dataset, q: int, metric: str) -> xr.Dataset:
    """
    Create a seasonal RR/log2RR/Wilson dataset from monthly count variables.
    """
    lon = ds_monthly["lon"].values
    lat = ds_monthly["lat"].values

    out_vars = {}
    for season_name, months, _desc in CFG.SEASONS:
        for phase in CFG.MAIN_PHASE_ORDER:
            phase_key = PHASE_KEY[phase]
            base = f"q{q}_{season_name}_{phase_key}"
            result = aggregate_season_from_monthly_counts(ds_monthly, q, months, phase)
            for suffix, arr in result.items():
                dtype = "float32" if arr.dtype.kind == "f" else arr.dtype
                out_vars[f"{base}_{suffix}"] = (("lat", "lon"), arr.astype(dtype))

    ds_seasonal = xr.Dataset(out_vars, coords={"lat": lat, "lon": lon})
    ds_seasonal.attrs.update({
        "description": f"Seasonal spatial RR/log2RR/Wilson significance for {metric} q{q}",
        "source": "Aggregated from monthly Figure 4 RR/Wilson count NetCDF",
        "metric": metric,
        "threshold": int(q),
        "main_plot_variable": "log2RR",
        "significance": "Wilson score interval; Neutral event probability outside ENSO-phase 95% CI",
    })
    return ds_seasonal


def log2rr_to_equal_position(log2rr: np.ndarray) -> np.ndarray:
    """Transform log2(RR) values to equal-spaced colorbar positions."""
    ticks = np.asarray(CFG.MAIN_LOG2RR_TICKS, dtype=float)
    pos = np.arange(len(ticks), dtype=float)
    out = np.full_like(log2rr, np.nan, dtype=float)
    ok = np.isfinite(log2rr)
    if np.any(ok):
        out[ok] = np.interp(log2rr[ok], ticks, pos, left=pos[0], right=pos[-1])
    return out


def cmap_log2rr_equal() -> Tuple[mcolors.ListedColormap, mcolors.BoundaryNorm, List[float], List[str]]:
    """Equal visual-interval colorbar for the seasonal log2(RR) maps."""
    cmap = mcolors.ListedColormap(list(CFG.LOG2RR_COLORS), name="log2RR_equal_interval")
    cmap.set_bad((1, 1, 1, 0))
    bounds = np.arange(len(CFG.MAIN_LOG2RR_TICKS), dtype=float)
    norm = mcolors.BoundaryNorm(bounds, cmap.N, clip=True)
    tick_pos = list(range(len(CFG.MAIN_LOG2RR_TICKS)))
    tick_lab = [str(v) for v in CFG.MAIN_LOG2RR_TICKS]
    return cmap, norm, tick_pos, tick_lab


def cmap_log2rr() -> Tuple[mcolors.ListedColormap, mcolors.BoundaryNorm, np.ndarray]:
    bounds = np.asarray(CFG.LOG2RR_BOUNDS, dtype=float)
    cmap = mcolors.ListedColormap(list(CFG.LOG2RR_COLORS), name="log2RR_CEE")
    cmap.set_bad((1, 1, 1, 0))
    norm = mcolors.BoundaryNorm(bounds, cmap.N, clip=False)
    return cmap, norm, bounds


