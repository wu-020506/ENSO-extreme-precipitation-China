def make_panel_matrix(risk: pd.DataFrame, basin: str, phase: str) -> Tuple[np.ndarray, np.ndarray]:
    """
    Return:
        z_plot: data used for color
        sig_mask: boolean matrix of significance
    Shape:
        len(CFG.THRESHOLDS) × 12
    """
    z = np.full((len(CFG.THRESHOLDS), 12), np.nan, dtype=float)
    sig = np.zeros((len(CFG.THRESHOLDS), 12), dtype=bool)

    sub = risk[(risk["basin"] == basin) & (risk["phase"] == phase)].copy()

    threshold_to_row = {int(q): i for i, q in enumerate(CFG.THRESHOLDS)}

    for _, row in sub.iterrows():
        q = int(row["threshold"])
        m = int(row["month"])
        if q not in threshold_to_row or not (1 <= m <= 12):
            continue
        i = threshold_to_row[q]
        j = m - 1
        z[i, j] = float(row["log2RR"]) if np.isfinite(row["log2RR"]) else np.nan
        sig[i, j] = bool(row["significant"])

    if CFG.MASK_NON_SIGNIFICANT:
        z_plot = z.copy()
        z_plot[~sig] = np.nan
    else:
        z_plot = z

    return z_plot, sig


def add_panel_label(ax, label: str) -> None:
    ax.text(
        0.01, 1.03, label,
        transform=ax.transAxes,
        ha="left", va="bottom",
        fontsize=12.5,
        fontweight="bold",
        clip_on=False,
    )


def plot_12panel_heatmap(
    risk: pd.DataFrame,
    method: str,
    figure_id: str,
    highlight_threshold: int,
    description: str,
) -> Dict[str, str]:
    """
    Plot 6 basins × 2 ENSO phases heatmap.
    """
    set_figure_style()
    fig_dir, _ = output_dirs()

    cmap = plt.get_cmap("RdBu_r").copy()
    cmap.set_bad(color="0.88")

    vlim = float(CFG.COLOR_LIMIT)
    norm = Normalize(vmin=-vlim, vmax=vlim)

    fig, axes = plt.subplots(
        nrows=6,
        ncols=2,
        figsize=CFG.FIG_SIZE,
        dpi=CFG.FIG_DPI,
        sharex=True,
        sharey=True,
        constrained_layout=False,
    )

    panel_labels = [f"({chr(ord('a') + i)})" for i in range(12)]
    panel_idx = 0

    # Cell-edge coordinates for pcolormesh.
    # z has shape = n_thresholds × 12 months, so x_edges must have 13 values
    # and y_edges must have n_thresholds + 1 values.
    x_edges = np.arange(0.5, 12.5 + 1e-9, 1.0)
    y_edges = np.arange(min(CFG.THRESHOLDS) - 0.5, max(CFG.THRESHOLDS) + 0.5 + 1e-9, 1.0)

    for r, basin in enumerate(CFG.BASIN_ORDER):
        for c, phase in enumerate(CFG.PHASES):
            ax = axes[r, c]
            z, sig = make_panel_matrix(risk, basin, phase)

            ax.pcolormesh(
                x_edges,
                y_edges,
                z,
                cmap=cmap,
                norm=norm,
                shading="auto",
                edgecolors="white",
                linewidth=0.12,
            )

            # Highlight the main/supporting threshold line.
            ax.axhline(
                highlight_threshold,
                color="black",
                lw=1.25,
                ls="--",
                alpha=0.95,
                zorder=4,
            )
            ax.text(
                12.55,
                highlight_threshold,
                f"q{highlight_threshold}",
                ha="left",
                va="center",
                fontsize=8.6,
                fontweight="bold",
                color="black",
                clip_on=False,
            )

            # If all cells are displayed, mark significance with dots.
            if not CFG.MASK_NON_SIGNIFICANT:
                yy, xx = np.where(sig)
                if len(xx) > 0:
                    ax.scatter(
                        xx + 1,
                        np.array(CFG.THRESHOLDS)[yy],
                        s=7,
                        color="black",
                        linewidths=0,
                        zorder=5,
                    )

            add_panel_label(ax, panel_labels[panel_idx])
            panel_idx += 1

            # Column titles
            if r == 0:
                ax.set_title(
                    CFG.PHASE_LABELS.get(phase, phase),
                    fontsize=13.5,
                    fontweight="bold",
                    pad=10,
                )

            # Basin label on the left side of each row.
            if c == 0:
                ax.text(
                    -0.22, 0.5,
                    CFG.BASIN_SHORT.get(basin, basin),
                    transform=ax.transAxes,
                    rotation=90,
                    ha="center",
                    va="center",
                    fontsize=12.2,
                    fontweight="bold",
                    clip_on=False,
                )
                ax.set_ylabel("Percentile threshold", fontsize=11.4, fontweight="bold")

            if r == 5:
                ax.set_xlabel("Month", fontsize=11.4, fontweight="bold")

            ax.set_xlim(0.5, 12.5)
            ax.set_ylim(min(CFG.THRESHOLDS) - 0.5, max(CFG.THRESHOLDS) + 0.5)
            ax.set_xticks(range(1, 13))
            ax.set_xticklabels(CFG.MONTH_LABELS, rotation=35, ha="right")
            ax.set_yticks([75, 80, 85, 90, 95])

            ax.tick_params(axis="both", length=3.0, width=0.85)
            for tick in ax.get_xticklabels() + ax.get_yticklabels():
                tick.set_fontweight("bold")

            for spine in ax.spines.values():
                spine.set_linewidth(0.85)

    # Shared bottom colorbar. This produces a continuous gradient color block
    # similar to the previous monthly-FAR style, but using log2(RR).
    sm = ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])
    cbar = fig.colorbar(
        sm,
        ax=axes.ravel().tolist(),
        orientation="horizontal",
        fraction=0.038,
        pad=0.060,
        aspect=46,
        extend="both",
    )
    cbar.set_label(r"$\log_2(\mathrm{RR})$", fontsize=12.5, fontweight="bold", labelpad=6)
    cbar.set_ticks([-2, -1, 0, 1, 2])
    cbar.ax.tick_params(labelsize=10.2, length=3, width=0.8)
    for t in cbar.ax.get_xticklabels():
        t.set_fontweight("bold")
    cbar.outline.set_linewidth(0.85)

    fig.subplots_adjust(
        left=0.105,
        right=0.965,
        bottom=0.120,
        top=0.955,
        hspace=0.35,
        wspace=0.18,
    )

    basename = (
        f"{figure_id}_{method}_anomaly_month_threshold_log2RR_"
        f"q{min(CFG.THRESHOLDS)}_q{max(CFG.THRESHOLDS)}_"
        f"highlight_q{highlight_threshold}_12panels_bottom_gradient_colorbar"
    )

    png = fig_dir / f"{basename}.png"
    tif = fig_dir / f"{basename}.tif"
    pdf = fig_dir / f"{basename}.pdf"

    fig.savefig(png, dpi=CFG.FIG_DPI, bbox_inches="tight", facecolor="white")
    if CFG.EXPORT_TIFF:
        try:
            fig.savefig(
                tif,
                dpi=CFG.FIG_DPI,
                bbox_inches="tight",
                facecolor="white",
                format="tiff",
                pil_kwargs={"compression": "tiff_lzw"},
            )
        except TypeError:
            fig.savefig(tif, dpi=CFG.FIG_DPI, bbox_inches="tight", facecolor="white", format="tiff")

    if CFG.EXPORT_PDF:
        fig.savefig(pdf, dpi=CFG.FIG_DPI, bbox_inches="tight", facecolor="white")

    plt.close(fig)

    return {
        "figure_id": figure_id,
        "method": method,
        "highlight_threshold": highlight_threshold,
        "description": description,
        "png": str(png),
        "tif": str(tif),
        "pdf": str(pdf),
    }


