def nc_to_method_dataframe(ds: xr.Dataset, method: str) -> pd.DataFrame:
    """
    Convert one method from the processed NetCDF into a long DataFrame.

    Expected NetCDF variables from the previous processing code:
        basin_mean_metric(method, basin, time)
        enso_phase_code(time)
        year(time)
        month(time)
        enso_index(time)

    The existing event variables in the NetCDF are not used here because
    Figure 3 recalculates threshold events across q75-q95 after anomaly
    calculation.
    """
    method_i = find_coord_index(ds, "method", method)

    if "basin_mean_metric" not in ds:
        raise KeyError("Variable 'basin_mean_metric' not found in NetCDF.")
    if "basin" not in ds.coords or "time" not in ds.coords:
        raise KeyError("Required coordinates 'basin' and/or 'time' are missing in NetCDF.")

    metric_da = ds["basin_mean_metric"]

    times = pd.to_datetime(ds["time"].values)
    basins = [str(v) for v in ds["basin"].values]

    if "enso_phase_code" not in ds:
        raise KeyError("Variable 'enso_phase_code' not found in NetCDF.")
    phase_codes = ds["enso_phase_code"].values.astype(int)

    if "year" in ds:
        years = ds["year"].values.astype(int)
    else:
        years = np.array([t.year for t in times], dtype=int)

    if "month" in ds:
        months = ds["month"].values.astype(int)
    else:
        months = np.array([t.month for t in times], dtype=int)

    if "enso_index" in ds:
        enso_index = ds["enso_index"].values.astype(float)
    else:
        enso_index = np.full(len(times), np.nan, dtype=float)

    rows = []
    for bi, basin_name in enumerate(basins):
        if basin_name not in CFG.BASIN_ORDER:
            # Keep only the six target basins if the NetCDF contains others.
            continue

        vals = metric_da.isel(method=method_i, basin=bi).values.astype(float)

        for ti, t in enumerate(times):
            phase = phase_from_code(int(phase_codes[ti]))
            if phase not in ["El Nino", "La Nina", "Neutral"]:
                continue

            rows.append({
                "method": method,
                "basin": basin_name,
                "time": t,
                "year": int(years[ti]),
                "month": int(months[ti]),
                "phase_code": int(phase_codes[ti]),
                "phase": phase,
                "enso_index": float(enso_index[ti]),
                "metric_raw": float(vals[ti]),
            })

    df = pd.DataFrame(rows)
    if df.empty:
        raise ValueError(f"No rows extracted for method={method}. Check method and basin names.")
    return df


def add_calendar_month_anomaly(df: pd.DataFrame) -> pd.DataFrame:
    """
    Convert raw basin-mean monthly metrics to basin × calendar-month anomalies.
    """
    out = df.copy()

    baseline = out[
        (out["year"].astype(int) >= CFG.ANOMALY_BASELINE_START_YEAR)
        & (out["year"].astype(int) <= CFG.ANOMALY_BASELINE_END_YEAR)
    ].copy()

    if baseline.empty:
        raise ValueError("No baseline data available for anomaly calculation.")

    clim = (
        baseline
        .groupby(["basin", "month"], as_index=False)["metric_raw"]
        .mean()
        .rename(columns={"metric_raw": "metric_climatology"})
    )

    out = out.merge(clim, on=["basin", "month"], how="left")
    out["metric_anomaly"] = out["metric_raw"] - out["metric_climatology"]
    out["metric"] = out["metric_anomaly"]

    if out["metric"].isna().any():
        missing = out[out["metric"].isna()][["basin", "month"]].drop_duplicates()
        raise ValueError(f"Missing anomaly values for some basin-month pairs:\n{missing}")

    return out


