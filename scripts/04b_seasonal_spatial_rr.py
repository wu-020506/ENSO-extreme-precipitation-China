def read_vector(path: Path, layer: Optional[str] = None) -> gpd.GeoDataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Vector file not found: {path}")

    encodings = ["gb18030", "gbk", "cp936", "utf-8"]
    last_error = None
    for enc in encodings:
        try:
            if layer is None:
                gdf = gpd.read_file(path, encoding=enc)
            else:
                gdf = gpd.read_file(path, layer=layer, encoding=enc)

            if gdf.crs is None:
                gdf = gdf.set_crs("EPSG:4326")
            else:
                gdf = gdf.to_crs("EPSG:4326")
            return gdf
        except Exception as exc:
            last_error = exc

    raise RuntimeError(f"Failed to read vector file: {path}; last error: {last_error}")


def union_geometry(gdf: gpd.GeoDataFrame):
    try:
        return gdf.geometry.union_all()
    except Exception:
        return gdf.geometry.unary_union


def load_china_boundary() -> gpd.GeoDataFrame:
    global_gdf = read_vector(CFG.SHP_GLOBAL)
    possible_cols = [
        "CN_NAME", "NAME", "SOVEREIGNT", "ADMIN", "COUNTRY",
        "CNTRY_NAME", "NAME_ZH", "国家", "国名",
    ]

    for col in possible_cols:
        if col in global_gdf.columns:
            s = global_gdf[col].astype(str)
            mask = s.str.contains("China|中国|CHN|中华人民共和国", case=False, na=False, regex=True)
            if mask.any():
                china = global_gdf.loc[mask].copy()
                china = china.dissolve().to_crs("EPSG:4326")
                return china

    raise ValueError("Could not identify China polygon from SHP_GLOBAL.")


def normalize_basin_name(x: object) -> str:
    s = str(x).strip()
    s_low = s.lower().replace("_", " ")
    if s in BASIN_ENGLISH_MAP:
        return BASIN_ENGLISH_MAP[s]
    if s_low in BASIN_ENGLISH_MAP:
        return BASIN_ENGLISH_MAP[s_low]
    return s


def find_basin_name_column(gdf: gpd.GeoDataFrame) -> Optional[str]:
    for col in BASIN_NAME_CANDIDATES:
        if col in gdf.columns:
            return col

    # fallback: first object column with at least 4 unique values
    for col in gdf.columns:
        if col == "geometry":
            continue
        if gdf[col].dtype == object and gdf[col].nunique(dropna=True) >= 4:
            return col

    return None


def load_six_basins(china: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    basins = read_vector(CFG.BASIN_POLYGON_FILE)
    basins = gpd.clip(basins, china)

    name_col = find_basin_name_column(basins)
    if name_col is not None:
        basins["basin_name"] = basins[name_col].map(normalize_basin_name)
    else:
        # If the file already contains only six polygons but no names, create generic labels.
        basins["basin_name"] = [f"Basin {i + 1}" for i in range(len(basins))]

    # Dissolve repeated polygons belonging to the same basin.
    basins = basins.dissolve(by="basin_name", as_index=False)
    basins = basins.to_crs("EPSG:4326")
    return basins[["basin_name", "geometry"]]


def load_boundaries() -> Dict[str, Optional[gpd.GeoDataFrame]]:
    print("Loading boundaries...")
    china_polygon = load_china_boundary()

    province_raw = read_vector(CFG.SHP_PROVINCE) if CFG.SHP_PROVINCE.exists() else None
    ten_dash_raw = read_vector(CFG.SHP_TEN_DASH) if CFG.SHP_TEN_DASH.exists() else None
    basins_raw = load_six_basins(china_polygon)

    if ten_dash_raw is not None:
        ten_dash_raw = ten_dash_raw.cx[72:138, 0:56]
        # The ten-dash shapefile may contain points or buffered polygons.
        # Keep only real line geometries to remove grey dots/shadows.
        ten_dash_line = _geometry_to_line_only(ten_dash_raw, polygon_to_boundary=False)
        if ten_dash_line.empty:
            print("WARNING: no LineString/MultiLineString remained in ten-dash shapefile; ten-dash layer skipped.")
