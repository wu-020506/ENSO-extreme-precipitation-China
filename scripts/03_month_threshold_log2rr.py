def phase_from_code(code: int) -> str:
    return {1: "El Nino", -1: "La Nina", 0: "Neutral"}.get(int(code), "Unknown")


def find_coord_index(ds: xr.Dataset, coord: str, value: str) -> int:
    if coord not in ds.coords:
        raise KeyError(f"Coordinate '{coord}' not found in dataset. Available coords: {list(ds.coords)}")
    vals = [str(v) for v in ds[coord].values]
    value_norm = str(value).strip().lower()
    for i, v in enumerate(vals):
        if v.strip().lower() == value_norm:
            return i
    # Common fallback: RX5day vs Rx5day
    for i, v in enumerate(vals):
        if v.strip().lower().replace("_", "") == value_norm.replace("_", ""):
            return i
    raise ValueError(f"Cannot find {coord}={value!r}. Available {coord} values: {vals}")


def safe_log2_rr(
    c_phase: int,
    n_phase: int,
    c_neutral: int,
    n_neutral: int,
    use_correction: bool = True,
) -> Tuple[float, float, float, float]:
    """
    Return RR, log2RR, P_phase, P_neutral.

    With sparse q95 monthly cells, P_neutral may be zero. If
    USE_HALDANE_ZERO_CORRECTION is True, a standard 0.5 cell correction is used:
        P = (count + 0.5) / (n + 1)
    This avoids infinite RR and keeps heatmaps interpretable.
    """
    if n_phase <= 0 or n_neutral <= 0:
        return np.nan, np.nan, np.nan, np.nan

    if use_correction and (c_phase == 0 or c_neutral == 0):
        p_phase = (c_phase + 0.5) / (n_phase + 1.0)
        p_neutral = (c_neutral + 0.5) / (n_neutral + 1.0)
    else:
        p_phase = c_phase / n_phase
        p_neutral = c_neutral / n_neutral

    if not np.isfinite(p_phase) or not np.isfinite(p_neutral) or p_neutral <= 0:
        return np.nan, np.nan, p_phase, p_neutral

    rr = p_phase / p_neutral
    log2rr = np.log2(rr) if rr > 0 else np.nan
    return rr, log2rr, p_phase, p_neutral


def permutation_p_value(
    events_phase: np.ndarray,
    events_neutral: np.ndarray,
    rng: np.random.Generator,
) -> Tuple[float, float, int]:
    """
    Permutation test for one basin × month × threshold × phase cell.

    Null hypothesis
    ---------------
    The probability of threshold exceedance is independent of ENSO phase.

    Procedure
    ---------
    Combine phase and neutral event vectors, then randomly assign the same
    number of samples to the ENSO phase group and neutral group. Recalculate
    log2(RR) at each permutation to build the null distribution.

    Returns
    -------
    p_value, observed_log2RR, number_of_valid_permutations
    """
    ep = np.asarray(events_phase, dtype=int)
    en = np.asarray(events_neutral, dtype=int)

    n_phase = ep.size
    n_neutral = en.size

    c_phase = int(ep.sum())
    c_neutral = int(en.sum())

    _, obs_log2rr, _, _ = safe_log2_rr(
        c_phase, n_phase, c_neutral, n_neutral,
        use_correction=CFG.USE_HALDANE_ZERO_CORRECTION,
    )

    if not np.isfinite(obs_log2rr):
        return np.nan, obs_log2rr, 0

    pooled = np.concatenate([ep, en])
    n_total = pooled.size

    perm_vals = []
    for _ in range(CFG.N_PERMUTATIONS):
        idx_phase = rng.choice(n_total, size=n_phase, replace=False)
        mask = np.zeros(n_total, dtype=bool)
        mask[idx_phase] = True

        c1 = int(pooled[mask].sum())
        c0 = int(pooled[~mask].sum())

        _, perm_log2rr, _, _ = safe_log2_rr(
            c1, n_phase, c0, n_neutral,
            use_correction=CFG.USE_HALDANE_ZERO_CORRECTION,
        )

        if np.isfinite(perm_log2rr):
            perm_vals.append(perm_log2rr)

    if len(perm_vals) < max(20, CFG.N_PERMUTATIONS * 0.1):
        return np.nan, obs_log2rr, len(perm_vals)

    perm_vals = np.asarray(perm_vals, dtype=float)

    if CFG.TWO_SIDED:
        p = (np.sum(np.abs(perm_vals) >= abs(obs_log2rr)) + 1.0) / (len(perm_vals) + 1.0)
    else:
        # One-sided test in the observed direction.
        if obs_log2rr >= 0:
            p = (np.sum(perm_vals >= obs_log2rr) + 1.0) / (len(perm_vals) + 1.0)
        else:
            p = (np.sum(perm_vals <= obs_log2rr) + 1.0) / (len(perm_vals) + 1.0)

    return float(p), float(obs_log2rr), int(len(perm_vals))


